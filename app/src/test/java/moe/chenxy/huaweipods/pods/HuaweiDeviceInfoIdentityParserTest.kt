    @Test
    fun `finds one valid identity among bounded concatenated RFCOMM frames`() {
        val batteryFrame = "5A001B000108010163020364636103030000010402140A0502000006010A3B01"
        val identityFrame =
            "5A0092000107020201530308484C324F52434D5207204861726D6F6E794F5320362E302E302E323932284630303148303033433030290910324E47545132353131373030383734320A0F42544654303031392D3030303135330F08425446543030313918254C2D545134383730323531373030373430352C522D545134383733323531453031393636361901021B06018D51D8C104637C"

        assertEquals(
            HuaweiDeviceInfoIdentity("000153", "02"),
            HuaweiDeviceInfoIdentityParser.parse((batteryFrame + identityFrame).hexBytes()),
        )
    }

    @Test
    fun `conflicting valid identities fail closed`() {
        val freeBuds5 =
            "5A0076000107020201410309484C31524845494E4D07204861726D6F6E794F5320352E302E302E32303828463030314830303343303129091058564C424232333431323130303439370A0F42544654303031332D3030303134310F0842544654303031331810424231393130323333594130303339361901011B8F"
        val eyewear2 =
            "5A007A0001070202014F030B484C314F54454D325F564107204861726D6F6E794F5320342E322E302E313338284630303148303033433030290910325243545132363132353030303139320A104254464C46544730302D3030303134460F094254464C4654473030181054513235353632363136413030303739190100CE46"

        assertNull(HuaweiDeviceInfoIdentityParser.parse((freeBuds5 + eyewear2).hexBytes()))
    }

    @Test
    fun `rejects truncated bad CRC and non DeviceInfo data`() {
        val valid =
            "5A0076000107020201410309484C31524845494E4D07204861726D6F6E794F5320352E302E302E32303828463030314830303343303129091058564C424232333431323130303439370A0F42544654303031332D3030303134310F0842544654303031331810424231393130323333594130303339361901011B8F"
        val badCrc = valid.hexBytes().apply { this[lastIndex] = (this[lastIndex].toInt() xor 1).toByte() }

        assertNull(HuaweiDeviceInfoIdentityParser.parse(valid.dropLast(2).hexBytes()))
        assertNull(HuaweiDeviceInfoIdentityParser.parse(badCrc))
        assertNull(HuaweiDeviceInfoIdentityParser.parse("5A0005002B2A0100427E".hexBytes()))
        assertNull(HuaweiDeviceInfoIdentityParser.parse(ByteArray(64 * 1024 + 1)))
    }

    private fun String.hexBytes(): ByteArray = chunked(2)
        .map { it.toInt(16).toByte() }
        .toByteArray()
}
