        val captures = mapOf(
            "5A0076000107020201410309484C31524845494E4D07204861726D6F6E794F5320352E302E302E32303828463030314830303343303129091058564C424232333431323130303439370A0F42544654303031332D3030303134310F0842544654303031331810424231393130323333594130303339361901011B8F" to
                HuaweiDeviceInfoIdentity("000141", "01"),
            "5A007A0001070202014F030B484C314F54454D325F564107204861726D6F6E794F5320342E322E302E313338284630303148303033433030290910325243545132363132353030303139320A104254464C46544730302D3030303134460F094254464C4654473030181054513235353632363136413030303739190100CE46" to
                HuaweiDeviceInfoIdentity("00014F", "00"),
            "5A0092000107020201530308484C324F52434D5207204861726D6F6E794F5320362E302E302E323932284630303148303033433030290910324E47545132353131373030383734320A0F42544654303031392D3030303135330F08425446543030313918254C2D545134383730323531373030373430352C522D545134383733323531453031393636361901021B06018D51D8C104637C" to
                HuaweiDeviceInfoIdentity("000153", "02"),
            "5A0025000107020201630A0F42544654303032352D3030303136330F08425446543030323519010242B3" to
                HuaweiDeviceInfoIdentity("000163", "02"),
            "5A00950001070202015D030B484C314F54454D325F564107204861726D6F6E794F5320362E302E302E323136284630303148303033433030290910344750524C32363230313030343232370A0F42544654303032312D3030303135440F08425446543030323118254C2D524C32383033323631573037303231392C522D524C323830333236315430353930313219010C1B061D45A24E6EA89004" to
                HuaweiDeviceInfoIdentity("00015D", "0C"),
            "5A008D00010702020145030B484C314F54454D325F564107204861726D6F6E794F5320322E312E302E323138284630303148303033433030290910355055545132333130353030303239390A0F42544654303031342D3030303134350F08425446543030313418254C2D5451393038343232434C3032333535312C522D545139303838323334553030363135301901077DE0" to
